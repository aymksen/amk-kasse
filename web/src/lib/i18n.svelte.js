let language = $state('de');

export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'de';
  document.documentElement.lang = language;
}

export const getLanguage = () => language;

/** Adds strings from another part of the app, such as the admin screens. */
export function addStrings(more) {
  Object.assign(strings, more);
}

export function t(key, vars) {
  const entry = strings[key];
  if (!entry) return key;
  const text = entry[language === 'en' ? 1 : 0];
  return vars ? text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '') : text;
}

export function errorText(err) {
  const known = strings['err.' + err?.code];
  return known ? t('err.' + err.code) : t('err.internal');
}
